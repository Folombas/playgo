// Colors определяет цвет каждой фигуры
var Colors = map[TetrominoType]color.RGBA{
	TypeI: {0, 240, 240, 255},   // Cyan
	TypeO: {240, 240, 0, 255},   // Yellow
	TypeT: {160, 0, 240, 255},   // Purple
	TypeL: {240, 160, 0, 255},   // Orange
	TypeJ: {0, 0, 240, 255},     // Blue
	TypeS: {0, 240, 0, 255},     // Green
	TypeZ: {240, 0, 0, 255},     // Red
}

// NewRandomTetromino создаёт случайную фигуру
func NewRandomTetromino() *Tetromino {
	t := TetrominoType(rand.Intn(7))
	return &Tetromino{
		Type:   t,
		X:      3,
		Y:      -2,
	}
}

// Shape возвращает матрицу текущего вращения
func (t *Tetromino) Shape() [][]int {
	return Shapes[t.Type][t.Rotation]
}

// Color возвращает цвет фигуры
func (t *Tetromino) Color() color.Color {
	return Colors[t.Type]
}

// Rotate поворачивает фигуру по часовой стрелке
func (t *Tetromino) Rotate() {
	t.Rotation = (t.Rotation + 1) % 4
}

// RotateCCW поворачивает против часовой
func (t *Tetromino) RotateCCW() {
	t.Rotation = (t.Rotation + 3) % 4
}
